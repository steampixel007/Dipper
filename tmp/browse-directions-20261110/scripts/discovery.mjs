import { chromium } from 'playwright-core'
import { fileURLToPath } from 'node:url'

const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1320, height: 920 } })
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
let checks = 0
function ok(condition, message) {
  checks += 1
  if (!condition) throw new Error(message)
}
const target = (name) => page.locator(`[data-target="${name}"]`)
async function open(width = 1320) {
  await page.setViewportSize({ width, height: 920 })
  await page.goto('http://127.0.0.1:4397/?capture=shelf', { waitUntil: 'networkidle' })
  await page.locator('.poster-card').first().waitFor()
}
async function closed() {
  await page.getByRole('dialog').waitFor({ state: 'detached' })
}
