import { chromium } from 'playwright-core'
import { fileURLToPath } from 'node:url'

const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1320, height: 920 } })
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
let checks = 0
function ok(condition, message) {
  checks += 1
  if (!condition) throw new Error(message)
}
const target = (name) => page.locator(`[data-target="${name}"]`)
async function open(width = 1320) {
  await page.setViewportSize({ width, height: 920 })
  await page.goto('http://127.0.0.1:4397/?capture=shelf', { waitUntil: 'networkidle' })
  await page.locator('.poster-card').first().waitFor()
}
async function closed() {
  await page.getByRole('dialog').waitFor({ state: 'detached' })
}
try {
  await open()
  await target('anime-4031').click()
  ok(await page.getByRole('radio').count() === 0 && await page.locator('.release-row').count() === 0, 'opening a work must show its synopsis before subtitle groups or resources')
  ok(await target('confirm-follow').count() === 0, 'the synopsis must not allow confirmation before selecting a subtitle group')
  await target('choose-group').click()
  ok(await page.getByRole('dialog').count() === 0 && await page.locator('.follow-setup').isVisible(), 'subtitle groups belong on a separate setup page, outside the detail dialog')
  ok(await page.locator('[role="dialog"] [role="radio"]').count() === 0, 'the detail dialog must contain no subtitle group selector')
  ok(await target('confirm-follow').getAttribute('aria-disabled') === 'true', 'new follows must require an explicit subtitle group choice')
  ok(await page.getByRole('radio').count() === 4 && await page.locator('.release-row').count() === 0, 'group names must be available before any resource or generic version')
  await target('group-0').click()
  ok((await page.locator('.group-resource-pane').innerText()).includes('ANi'), 'choosing a group must show resources attributed to that group')
  ok((await page.locator('.release-list').innerText()).includes('1.4 GB'), 'the resource preview must contain the chosen group release data')
  await target('group-1').click()
  ok((await page.locator('.group-resource-pane').innerText()).includes('银色子弹字幕组') && !(await page.locator('.release-list').innerText()).includes('1.4 GB'), 'changing subtitle groups must replace the previous resource data')
  await page.locator('input[aria-label="搜索字幕组"]').fill('不存在')
  ok(await page.getByRole('radio').count() === 0 && await page.locator('.group-no-results').isVisible(), 'subtitle group search must explain an empty result')
  await page.locator('input[aria-label="搜索字幕组"]').fill('')
  await target('group-0').click()
  await target('confirm-follow').evaluate((button) => { button.click(); button.click() })
  await page.locator('.follow-setup').waitFor({ state: 'detached' })
  ok(await page.locator('.nav-item small').innerText() === '3', 'choosing a work then a group and confirming should add exactly one follow')
  ok(await page.locator('.nav-item small').innerText() === '3', 'repeated confirmation must not duplicate the follow')
  ok(await page.locator('.follow-setup').count() === 0 && await page.getByRole('dialog').isVisible(), 'confirmation must return to the work with its followed result')
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  ok(await page.locator('.nav-item small').innerText() === '2', 'the first confirmation must remain undoable after an accidental second click')
  await page.keyboard.press('Escape')
  ok(await page.getByRole('dialog').count() === 1, 'normal dismissal must retain the outgoing panel during its exit')
  await closed()
  ok(await page.evaluate(() => document.activeElement?.dataset.target === 'anime-4031'), 'dismissal must restore the originating poster focus')

  await target('day-5').click()
  await page.locator('input[aria-label="搜索番剧"]').fill('天是红河岸')
  ok(await page.locator('.poster-card').count() === 1, 'search must find a work outside the selected weekday')
  await page.keyboard.press('Enter')
  await page.getByRole('dialog').waitFor()
  ok((await page.getByRole('dialog').getAttribute('aria-label')) === '天是红河岸', 'Enter should open a sole search result')
  await page.waitForFunction(() => document.activeElement?.dataset.target === 'close-detail')
  await page.keyboard.press('Escape')
  await closed()
  await page.keyboard.press('Control+k')
  ok(await page.evaluate(() => document.activeElement?.getAttribute('aria-label') === '搜索番剧'), 'Ctrl+K must focus search')
  await page.keyboard.press('Escape')
  ok(await page.locator('.poster-card').count() === 0, 'clearing search must restore the previous weekday filter')
  await target('day--1').click()
  await target('anime-4031').click()
  await page.getByRole('dialog').evaluate((panel) => { panel.style.height = '500px' })
  await page.getByRole('dialog').evaluate((panel) => Promise.all(panel.getAnimations({ subtree: true }).map((animation) => animation.finished.catch(() => {}))))
  const identity = await page.locator('.detail-current .detail-identity').boundingBox()
  const reading = page.locator('.detail-current .detail-reading')
  await reading.focus()
  await page.keyboard.press('PageDown')
  await page.waitForFunction(() => document.querySelector('.detail-current .detail-reading').scrollTop > 0)
  await page.waitForTimeout(250)
  const scrolled = await reading.evaluate((element) => element.scrollTop)
  ok(scrolled > 0, 'a long synopsis must support keyboard scrolling')
  const retainedIdentity = await page.locator('.detail-current .detail-identity').boundingBox()
  ok(Math.abs(identity.y - retainedIdentity.y) < 1, 'scrolling the synopsis must retain the work identity')
  await target('choose-group').click()
  await target('group-0').click()
  await target('back-to-work').click()
  await page.getByRole('dialog').evaluate((panel) => Promise.all(panel.getAnimations({ subtree: true }).map((animation) => animation.finished.catch(() => {}))))
  ok(Math.abs(await reading.evaluate((element) => element.scrollTop) - scrolled) < 1 && await page.locator('.nav-item small').innerText() === '2', 'returning from setup must preserve synopsis scroll without creating a follow')
  const before = await page.getByRole('dialog').boundingBox()
  const scrollTransition = await target('detail-next').evaluate((button) => new Promise((resolve) => {
    const observer = new MutationObserver(() => {
      const outgoing = document.querySelector('.detail-outgoing .detail-reading')
      if (!outgoing) return
      observer.disconnect()
      clearTimeout(timeout)
      resolve({ outgoing: outgoing.scrollTop, current: document.querySelector('.detail-current .detail-reading')?.scrollTop })
    })
    const timeout = setTimeout(() => { observer.disconnect(); resolve({}) }, 1000)
    observer.observe(document.querySelector('.detail-scenes'), { childList: true, subtree: true })
    button.click()
  }))
  ok(Math.abs(scrollTransition.outgoing - scrolled) < 1, `the outgoing reading layer must retain its previous scroll offset (${scrolled} -> ${JSON.stringify(scrollTransition)})`)
  ok(scrollTransition.current === 0, 'a different work must start its synopsis at the top')
  await page.waitForTimeout(250)
  ok(await page.getByRole('dialog').getAttribute('aria-label') !== '天是红河岸', 'next should compare another work without closing detail')
  const after = await page.getByRole('dialog').boundingBox()
  ok(Math.abs(before.height - after.height) < 1 && Math.abs(before.y - after.y) < 1, 'reading another work must keep the panel and actions anchored')
  ok(await target('choose-group').count() === 1 && await page.getByRole('radio').count() === 0, 'a group choice must not leak into the next work synopsis')
  await target('choose-group').click()
  await target('group-0').focus()
  await page.keyboard.press('ArrowRight')
  ok(await target('group-1').getAttribute('aria-checked') === 'true', 'subtitle group choices must support arrow-key selection')
  await page.keyboard.press('Escape')
  ok(await page.locator('[aria-label="剧情简介"]').isVisible() && await page.evaluate(() => document.activeElement?.dataset.target === 'choose-group'), 'Escape from subtitle groups must restore synopsis and its action focus')
  await page.keyboard.press('Escape')
  await closed()

  await target('day--1').focus()
  await page.keyboard.press('ArrowRight')
  ok(await target('day-1').getAttribute('aria-pressed') === 'true', 'weekday arrows must select and focus the adjacent filter')
  await page.keyboard.press('Home')
  ok(await target('day--1').getAttribute('aria-pressed') === 'true', 'Home must restore the whole-season filter')
  await page.getByRole('button', { name: '未追番', exact: true }).click()
  await target('anime-4031').click()
  await target('choose-group').click()
  await target('group-0').click()
  await target('confirm-follow').click()
  await target('detail-next').click()
  await target('detail-prev').click()
  ok(await page.getByRole('dialog').getAttribute('aria-label') === '天是红河岸', 'following under a filter must retain the open comparison list')
  await page.keyboard.press('Escape')
  await closed()
  ok(await page.evaluate(() => document.activeElement?.isConnected && document.activeElement?.classList.contains('poster-card')), 'a removed originating poster must return focus to a remaining visible poster')

  await open(390)
  await target('anime-4031').click()
  const button = await target('choose-group').boundingBox()
  ok(button.y + button.height <= 920, 'compact detail must expose the next step without extra scrolling')
  await target('choose-group').click()
  await target('group-0').click()
  await page.waitForFunction(() => {
    const content = document.querySelector('.group-resource-content')
    return content && Number(getComputedStyle(content).opacity) > 0.99
  })
  const confirm = await target('confirm-follow').boundingBox()
  ok(confirm.y + confirm.height <= 920, 'compact subtitle groups must keep confirmation visible')
  await page.screenshot({ path: fileURLToPath(new URL('../evidence/shelf-discovery-390.png', import.meta.url)) })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await closed()
  await target('anime-4031').click()
  await target('choose-group').click()
  await target('group-1').click()
  await target('confirm-follow').click()
  ok(await page.locator('.nav-item small').innerText() === '3', 'reduced motion must retain the full explicit following flow')
  await page.goto('http://127.0.0.1:4397/?capture=shelf&rehearse', { waitUntil: 'networkidle' })
  await page.getByRole('dialog').waitFor()
  ok(await page.locator('.nav-item small').innerText() === '3', 'the reduced-motion rehearsal poster must show the completed follow')
  ok((await page.locator('.detail-action-note').innerText()).includes('ANi'), 'the reduced-motion poster must retain its explicit subtitle group summary')
  await page.keyboard.press('Escape')
  await closed()
  await target('anime-4031').click()
  ok(await page.getByRole('dialog').count() === 1, 'manual browsing must remain usable after the reduced-motion poster')
  ok(errors.length === 0, `browser errors: ${errors.join('; ')}`)
  console.log(`passed ${checks} discovery checks`)
} finally {
  await browser.close()
}
